function t(value) {
    if (typeof value !== 'string') return value;
    return PHRASES[value] || COPY[value] || value;
}

function localizeNode(node) {
    if (!node || typeof node !== 'object') return;
    if (typeof node.label === 'string') node.label = t(node.label);
    if (typeof node.title === 'string') node.title = t(node.title);
    if (typeof node.info === 'string') node.info = t(node.info);
    if (node.options && typeof node.options === 'object') {
        for (const key of Object.keys(node.options)) node.options[key] = t(node.options[key]);
    }
    if (typeof node.text === 'string') node.text = t(node.text);
    else if (Array.isArray(node.text)) node.text = node.text.map(item => {
        if (typeof item === 'string') return t(item);
        localizeNode(item);
        return item;
    });
    if (node.isInput) return;
    for (const key of Object.keys(node)) {
        if (!['options', 'text'].includes(key) && node[key] && typeof node[key] === 'object') localizeNode(node[key]);
    }
}

function localizeInputData(data) {
    localizeNode(data);
    return data;
}

function localizeHelpData(data) {
    localizeNode(data);
    return data;
}

